#!/usr/bin/env python3
"""Write theme/tokens.toml as the QML singleton AetherShared.Tokens.

The output is committed (the island runs from the source tree with no generate
step). `--check` exits 1 if the committed file is stale, without writing.
"""
import sys
from pathlib import Path

from tokens import PATH, camel, load

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "components/shared/AetherShared/Tokens.qml"


def _value(value) -> tuple[str, str]:
    if isinstance(value, str) and value.startswith("#"):
        return "color", f'"{value}"'
    if isinstance(value, str):
        return "string", f'"{value}"'
    if isinstance(value, int):
        return "int", str(value)
    return "real", repr(value)


SECTIONS = ("palette", "role", "material", "tint", "space", "radius", "type", "font", "motion", "dock")


def _components(path: tuple, table: dict, out: list) -> str:
    """Emit one typed inline component per table (so qmllint and completion see every token)."""
    name = "".join(camel(p)[:1].upper() + camel(p)[1:] for p in path) + "Tokens"
    body = []
    for key, value in table.items():
        if isinstance(value, dict):
            child = _components(path + (key,), value, out)
            body.append(f"        readonly property {child} {camel(key)}: {child} {{}}")
            continue
        easing = path[-2:] == ("motion", "easing")
        qtype, literal = ("int", f"Easing.{value}") if easing else _value(value)
        body.append(f"        readonly property {qtype} {camel(key)}: {literal}")
    out.append([f"    component {name}: QtObject {{", *body, "    }"])
    return name


def render(t: dict) -> str:
    rel = PATH.relative_to(ROOT)
    components, props = [], []
    for section in SECTIONS:
        name = _components((section,), t.get(section) or {}, components)
        props.append(f"    readonly property {name} {camel(section)}: {name} {{}}")
    lines = [
        f"// GENERATED by theme/generators/build_tokens_qml.py from {rel} - do not edit.",
        "// Run `make tokens` after changing the tokens. Meaning lives in Theme.qml.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        *props,
        "",
    ]
    for block in components:
        lines += block
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(load())
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run `make tokens`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print("built", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
